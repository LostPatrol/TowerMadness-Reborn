// Original WAVES_getSize multiplier, modulus, and float normalization.
constexpr std::uint64_t SizeMultiplier = 279470273;
constexpr std::uint64_t SizeModulus = 65537;
constexpr float SizeScale = 1.0f / 65536.0f;

// Read one already-normalized packaged resource.
nlohmann::json readData(const std::filesystem::path& path) {
    std::ifstream stream(path);
    if (!stream) throw std::runtime_error("Cannot load " + path.string());
    return nlohmann::json::parse(stream);
}

// Preserve the exact text hashed by GAMEMODE_createEndless, including its final NUL.
std::string endlessModeText(const std::string& waveSet, const std::string& map) {
    const bool sandbox = waveSet == "Endless_Sandbox";
    const std::string waves = sandbox ? "Endless_Hard" : waveSet;
    if (waves != "Endless_Easy" && waves != "Endless_Medium" && waves != "Endless_Hard")
        throw std::invalid_argument("Unknown original endless wave set: " + waveSet);
    return "{\"waves\": \"" + waves +
        "\",\"logoatlas\": \"uimaptitles\",\"logoatlastrans\": \"hard\",\"tech\": \"Insane\",\"map\": \"" +
        map + "\",\"lifes\": 10,\"money\": " + (sandbox ? "10000" : "100") + "}";
}

// Truncate the original float result while keeping extreme endless waves representable.
std::int64_t truncatedHealth(float value) {
    if (!std::isfinite(value) || value >= static_cast<float>(std::numeric_limits<std::int64_t>::max()))
        return std::numeric_limits<std::int64_t>::max();
    return static_cast<std::int64_t>(value);
}

