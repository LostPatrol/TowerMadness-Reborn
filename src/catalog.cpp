// Enumerate original resources and retain the currently proven selection gates.
std::vector<CatalogEntry> loadCatalog(const std::filesystem::path& assets) {
    std::vector<CatalogEntry> entries;
    for (const auto& file : std::filesystem::directory_iterator(assets / "data")) {
        const std::string name = file.path().filename().string();
        const std::string suffix = ".gamemode.json";
        if (!name.ends_with(suffix)) continue;
        const auto mode = readData(file.path());
        CatalogEntry entry;
        entry.id = name.substr(0, name.size() - suffix.size());
        entry.map = mode.at("map").get<std::string>();
        entry.tech = mode.at("tech").get<std::string>();
        entry.waves = mode.at("waves").get<std::string>();
        const auto waves = readData(assets / "data" / (entry.waves + ".waves.json"));
        entry.endless = waves.is_object() && waves.value("endless", false);
        entry.selectableKnown = entry.id == "PlainPlane" || entry.id == "DividedAttention" ||
            entry.id == "MuttonsFolly" || entry.id == "Madness";
        entry.startsUnlocked = entry.id == "PlainPlane";
        entry.selectionNote = entry.startsUnlocked ? "Original opening campaign" :
            entry.selectableKnown ? "Original campaign progression gate" :
            "Packaged add-on; original progression or entitlement gate not reproduced";
        entries.push_back(std::move(entry));
    }
    std::sort(entries.begin(), entries.end(), [](const CatalogEntry& a, const CatalogEntry& b) {
        return a.id < b.id;
    });
    return entries;
}

// Resolve the original deterministic type, size, health, gold, and regeneration.
nlohmann::json generateEndlessWave(const nlohmann::json& source, int waveIndex,
                                 std::uint32_t seedOffset) {
    if (waveIndex < 0 || !source.is_object() || !source.value("endless", false))
        throw std::invalid_argument("Endless generation requires a nonnegative wave index and original source");
    const int bossFrequency = source.value("bossfreq", 8);
    if (bossFrequency <= 0) throw std::invalid_argument("Invalid endless boss frequency");
    const bool boss = (static_cast<std::int64_t>(waveIndex) + 1) % bossFrequency == 0;
    const auto& types = source.at(boss ? "bosstypes" : "types");
    if (types.empty()) throw std::invalid_argument("Endless source has no enemy types");

    // Unsigned wrapping and every float32 operation follow the original ARM helpers.
    const auto sampleIndex = (source.value("s1", 0u) + source.value("s2", 279470273u) +
        source.value("s3", 0u) + static_cast<std::uint32_t>(waveIndex) + seedOffset) % WaveSamples.size();
    float sample = std::bit_cast<float>(WaveSamples[sampleIndex]);
    float recurrenceSum = 0;
    for (const auto& type : types) recurrenceSum += type.value("recurrence", 1.0f);
    const float inverseSum = 1.0f / recurrenceSum;
    std::size_t typeIndex = types.size() - 1;
    for (std::size_t i = 0; i < types.size(); ++i) {
        sample -= types[i].value("recurrence", 1.0f) * inverseSum;
        if (sample <= 0) { typeIndex = i; break; }
    }
    auto wave = types[typeIndex];
    const float n = static_cast<float>(waveIndex);
    const auto& coefficients = source.at("health");
    float health = coefficients.at(0).get<float>() + n * coefficients.at(1).get<float>();
    float term = n * coefficients.at(2).get<float>();
    term = n * term;
    health = health + term;
    term = n * coefficients.at(3).get<float>();
    term = n * term;
    term = n * term;
    health = health + term;
    term = n * coefficients.at(4).get<float>();
    term = n * term;
    term = n * term;
    term = n * term;
    health = health + term;
    health = wave.value("healthmod", 1.0f) * health;
    health = health / static_cast<float>(wave.value("count", 10));

    const float size = wave.value("sizefactor", 1.0f) * 0.5f +
        static_cast<float>((SizeMultiplier * static_cast<std::uint64_t>(waveIndex)) % SizeModulus) * SizeScale;
    wave["health"] = truncatedHealth(health);
    wave["gold"] = static_cast<int>(wave.value("goldmod", 1.0f) *
        static_cast<float>(waveIndex / 8 + 2));
    wave["size"] = size;
    wave["offset"] = wave.value("offset", 0.0f) * size;
    wave["regen"] = wave.value("regen", 0.0f) <= 0 ? std::int64_t{0} :
        truncatedHealth(wave.value("regen", 0.0f) * static_cast<float>(wave["health"].get<std::int64_t>()));
    wave["spawn"] = wave.value("spawn", false) ? 1 : 0;
    wave["deathsounds"] = wave.value("deathsound", nlohmann::json::array());
    wave["endlessType"] = typeIndex;
    return wave;
}

// Construct the native runtime mode instead of inventing a packaged gamemode file.
nlohmann::json makeEndlessMode(const std::string& waveSet, const std::string& map) {
    return nlohmann::json::parse(endlessModeText(waveSet, map));
}

// Reproduce native SHA-1 seed perturbations through the Windows system hash API.
std::uint32_t endlessModeSeedOffset(const std::string& waveSet, const std::string& map) {
    std::string input = endlessModeText(waveSet, map);
    input.push_back('\0');
    BCRYPT_ALG_HANDLE algorithm = nullptr;
    BCRYPT_HASH_HANDLE hash = nullptr;
    DWORD objectSize = 0, resultSize = 0;
    std::array<unsigned char, 20> digest{};
    if (BCryptOpenAlgorithmProvider(&algorithm, BCRYPT_SHA1_ALGORITHM, nullptr, 0) < 0)
        throw std::runtime_error("Cannot initialize endless map seed hash");
    const auto finish = [&]() {
        if (hash) BCryptDestroyHash(hash);
        BCryptCloseAlgorithmProvider(algorithm, 0);
    };
    if (BCryptGetProperty(algorithm, BCRYPT_OBJECT_LENGTH, reinterpret_cast<PUCHAR>(&objectSize),
                          sizeof(objectSize), &resultSize, 0) < 0) {
        finish();
        throw std::runtime_error("Cannot allocate endless map seed hash");
    }
    std::vector<unsigned char> object(objectSize);
    if (BCryptCreateHash(algorithm, &hash, object.data(), objectSize, nullptr, 0, 0) < 0 ||
        BCryptHashData(hash, reinterpret_cast<PUCHAR>(input.data()), static_cast<ULONG>(input.size()), 0) < 0 ||
        BCryptFinishHash(hash, digest.data(), static_cast<ULONG>(digest.size()), 0) < 0) {
        finish();
        throw std::runtime_error("Cannot compute endless map seed hash");
    }
    finish();
    // Native ldrsh reads SHA-1 bytes 0..1 and deliberately unaligned bytes 5..6.
    const auto first = static_cast<std::int16_t>(digest[0] | digest[1] << 8);
    const auto second = static_cast<std::int16_t>(digest[5] | digest[6] << 8);
    return static_cast<std::uint32_t>(static_cast<int>(first) + static_cast<int>(second));
}

